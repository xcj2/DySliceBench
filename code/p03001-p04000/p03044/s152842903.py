#!/usr/bin/env python3
import sys

def solve(N: int, u: "List[int]", v: "List[int]", w: "List[int]"):
    stack = [u[0]-1]
    answer = [-1]*N
    tree = [{} for _ in range(N)]
    for i in range(N-1):
        is_even = (w[i] % 2 == 0)
        tree[u[i]-1][v[i]-1] = is_even
        tree[v[i]-1][u[i]-1] = is_even
    answer[u[0]-1]=0
    #1なら訪問済み
    while stack:
        p = stack.pop()
        neighbors = tree[p]
        for n in neighbors:
            if answer[n]<0:
                answer[n] = answer[p] if neighbors[n] else 1-answer[p]
                stack.append(n)

    for a in answer:
        print(a)
    return


