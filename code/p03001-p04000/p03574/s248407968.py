#!/usr/bin/env python3
import sys

def count(h, w, S: "List[str]") -> int:
    return (S[h-1][w] + S[h][w-1] + S[h-1][w-1] + S[h+1][w-1] + S[h-1][w+1] + S[h+1][w+1] + S[h+1][w] + S[h][w+1]).count("#")

def solve(H: int, W: int, S: "List[str]"):
    S = ["." * W] + S + ["." * W]
    for h in range(H+2):
        S[h] = "." + S[h] + "."
    ans = ["" for _ in range(H)]
    for h in range(H):
        for w in range(W):
            if S[h+1][w+1] != "#":
                ans[h] += str(count(h+1, w+1, S))
            else:
                ans[h] += "#"
    for a in ans:
        print("".join(a))
    return


