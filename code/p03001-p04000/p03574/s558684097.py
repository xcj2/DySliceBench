#!/usr/bin/env python3
import sys


def solve(H: int, W: int, S: "List[str]"):
    M = [[0 for j in range(W)] for i in range(H)]

    for h in range(H):
        for w in range(W):
            if S[h][w] is "#":
                M[h][w] = -1

    for h in range(H):
        for w in range(W):

            if M[h][w] !=  -1:
                continue

            for hi in [-1,0,1]:

                if not (0 <= h+hi < H):
                    continue

                for wi in [-1,0,1]:

                    if not (0 <= w+wi < W):
                        continue
                        
                    val = M[h+hi][w+wi]
                    if val == -1:
                        continue
                    else:
                        M[h+hi][w+wi] += 1

    for h in range(H):
        print( "".join( [ "#" if w == -1 else str(w) for w in M[h] ] ) )
    return


