#!/usr/bin/env python3
import sys
import itertools

def solve(N: int, K: int, S: str):
    border = []
    prev = False
    first = S[0]
    for i, c in enumerate(S):
        if c != prev:
            border.append(i)
            prev = c
    border.append(N)
    length = len(border)
    if first == '1':
        size = (length - 1) // 2
    else:
        size = length // 2

    if K >= size:
        print(border[-1] - border[0])
        return
    
    res = 0
    for i in range(size-K+1):
        if first == '1': 
            res = max([res, border[min([2*i + 2*K + 1, length-1])] - border[2*i]])
        else: 
            res = max([res, border[min([2*i + 2*K, length-1])] - border[max([2*i - 1, 0])]])
    print(res)
    return


