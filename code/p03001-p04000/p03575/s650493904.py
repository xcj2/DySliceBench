import sys, math, fractions, itertools

def connected_num(N, G):
    # ノード0から行けるノードの数が全体のノード数に一致するか
    visited = [0] * N
    stack = [0]
    while(len(stack) > 0):
        n = stack.pop()
        if visited[n] == 0:
            stack += G[n]
            visited[n] = 1
    return sum(visited) != N
def solve(N: int, M: int, a: "List[int]", b: "List[int]"):
    counter = 0
    for j in range(M):
        G = [[] for _ in range(N)]
        for i in list(range(j))+list(range(j+1, M)):
            G[a[i]-1].append(b[i]-1)
            G[b[i]-1].append(a[i]-1)
        if connected_num(N, G):
            counter += 1
    print(counter)
    return


