#!/usr/bin/env python3
import sys

MOD = 1000000007  # type: int

def solve(N: int, S: "List[str]"):
    i = 0
    res = 1
    before = 0 # 0: h, 1: v
    while i < N:
        if S[0][i] == S[1][i]:
            if i == 0:
                res = 3
            elif before == 0:
                res = res * 2 % MOD
            else:
                res = res
            before = 0
            i += 1
        else:
            if i == 0:
                res = 6
            elif before == 0:
                res = res * 2 % MOD
            else:
                res = res * 3 % MOD
            before = 1
            i += 2
    print(res)
    return


