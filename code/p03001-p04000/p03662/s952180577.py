#!/usr/bin/env python3
import sys
from collections import deque


def solve(N: int, path):
    f, s = [1], [N]
    black = set([1])
    white = set([N])
    while True:
        fn = []
        for ff in f:
            for fnext in path[ff]:
                if fnext not in white and fnext not in black:
                    black.add(fnext)
                    fn.append(fnext)
        f = fn
        sn = []
        for ss in s:
            for snext in path[ss]:
                if snext not in white and snext not in black:
                    white.add(snext)
                    sn.append(snext)
        s = sn
        if not s and not f:
            break
    print("Fennec" if len(black) > len(white) else "Snuke")
    return


