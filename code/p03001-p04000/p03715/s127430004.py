#!/usr/bin/env python3
import sys


def diff(L):
    return(max(L)-min(L))

def solve(H: int, W: int):
    N = 3
    if H % N == 0 or W % N == 0:
        print(0)
        return
    
    res = H * W
    for h in range(1, H):
        s1 = (H - h) * W

        s2 = h * (W // 2)
        s3 = h * (W - W // 2)
        res = min(res, diff([s1, s2, s3]))

        s2 = (h // 2) * W
        s3 = (h - h // 2) * W
        res = min(res, diff([s1, s2, s3]))

    for w in range(1, W):
        s1 = H * (W - w)

        s2 = (H // 2) * w
        s3 = (H - H // 2) * w
        res = min(res, diff([s1, s2, s3]))
        
        s2 = H * (w // 2)
        s3 = H * (w - w // 2)
        res = min(res, diff([s1, s2, s3]))

    print(res)
    return


