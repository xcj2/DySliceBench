import sys


def make_sorted_pairs(a_list, b_list):
    return list(sorted(
        tuple(sorted((a, b))) 
        for a, b in zip(a_list, b_list)
    ))


def is_in_range(bridges_range, west):
    b_west, b_east = bridges_range
    if b_east <= west:
        return False
    return True


def update_range(bridges_range, west, east):
    b_west, b_east = bridges_range
    return max(b_west, west), min(b_east, east)


