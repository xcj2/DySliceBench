#!/usr/bin/env python3
import sys
from collections import Counter


def solve(S: str):
    tmp = []
    i = 0
    while i < len(S):
        j = i+1
        if S[i: i+3] == 'ABC':
            j = i
            while True:
                if S[j:j+3] == 'ABC':
                    j += 3
                elif S[j:j+2] == 'BC':
                    j += 2
                else:
                    break
            jl = i
            while jl >= 0:
                if S[jl] != 'A':
                    break
                jl -= 1
            jl += 1


            if len(tmp)>0 and tmp[-1][1] == jl:
                tmp[-1][0] += S[jl: j]
                tmp[-1][1] = j
            else:
                tmp.append([S[jl: j], j])

        i = j
    ans = 0
    for elem, _ in tmp:
        cnt_a = Counter(elem)['A']
        for i in range(len(elem)):
            if elem[i] == 'A':
                cnt_a -= 1
                ans += (len(elem)-1-i-cnt_a)//2
                assert (len(elem)-1-i-cnt_a)%2==0

    print(ans)
    return


