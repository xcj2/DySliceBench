#!/usr/bin/env python3
import sys

memo = [{} for _ in range(51)]

def rec(x, k):
    """レベルxバーガーを下からk枚食べた時のパティの枚数"""
    M = 2 ** (x+2) - 3
    if k in memo[x].keys():
        return memo[x][k]
    if k <= x:
        return 0
    if x == 1:
        if k in [2, 3, 4]:
            return k - 1
        elif k == 5:
            return 3
        elif k == 1:
            return 0
        else:
            return 3
    else:
        if k < (M+1) // 2:
            ret = rec(x-1, k-1)
            memo[x][k] = ret
        elif k > (M+1) // 2:
            ret = rec(x-1, (M-3)//2) + 1 + rec(x-1, k-2-(M-3)//2)
            memo[x][k] = ret
        else:
            ret = rec(x-1, (M-3)//2) + 1
            memo[x][k] = ret
        return ret

def solve(N: int, X: int):
    print(rec(N, X))
