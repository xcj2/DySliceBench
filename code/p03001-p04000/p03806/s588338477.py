#!/usr/bin/env python3
import sys
import numpy as np


def solve(N: int, M_a: int, M_b: int, a: "List[int]", b: "List[int]", c: "List[int]"):
    c_max = 100
    a_max = 10
    total_max = (N+1) * a_max

    t = np.full((N+1, total_max + 1, total_max + 1), c_max * N, dtype=int)
    t[0][0][0] = 0

    for i in range(N):
        t[i+1] = t[i]
        buy = t[i, :-a[i], :-b[i]] + c[i]
        not_buy = t[i, a[i]:, b[i]:]
        cheaper = buy < not_buy
        t[i+1, a[i]:, b[i]:] = np.where(cheaper, buy, not_buy)
    
    t_a, t_b = M_a, M_b
    cheapest = total_max + 1
    while t_a <= total_max and t_b <= total_max:
        total = t[N][t_a][t_b]
        if total < cheapest:
            cheapest = total
        t_a += M_a
        t_b += M_b
    
    if cheapest == total_max + 1:
        print(-1)
    else:
        print(cheapest)

    return


