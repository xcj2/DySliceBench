import sys


def is_enough(n: int, d: int, B: int, h: "List[int]"):
    count = 0
    for hi in h:
        rest = hi - B * n
        if rest <= 0:
            break
        count += (rest + d - 1) // d
        if count > n:
            return False
    return n >= count


def solve(N: int, A: int, B: int, h: "List[int]"):
    h.sort(reverse=True)
    d = A - B

    right = (h[0] + B - 1) // B
    left = (h[0] - 1) // A
    
    while right - left > 1:
        mid = left + (right - left) // 2
        if is_enough(mid, d, B, h):
            right = mid
        else:
            left = mid
    
    print(right)
    return


