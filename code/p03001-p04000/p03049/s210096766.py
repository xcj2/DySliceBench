#!/usr/bin/env python3
import sys


def solve(N: int, S: "List[str]"):
    cnt = 0
    
    cnt_ba = 0
    cnt__a = 0
    cnt_b_ = 0

    for s in S:
        cnt += s.count("AB")
        if s[0] == "B" and s[-1] == "A":
            cnt_ba += 1
        elif s[0] == "B":
            cnt_b_ += 1
        elif s[-1] == "A":
            cnt__a += 1

    if cnt_ba > 0:
        cnt += cnt_ba - 1
        if cnt__a > 0:
            cnt += 1
            cnt__a -= 1

        if cnt_b_ > 0:
            cnt += 1
            cnt_b_ -= 1

    cnt += min(cnt__a,cnt_b_)


    print(cnt)



    return


