#!/usr/bin/env python3
import sys


def solve(N: int, s: "List[str]"):
    count_AB = 0
    count_endswith_A = 0
    count_startswith_B = 0
    count_BA = 0
    for ss in s:
        count_AB += ss.count('AB')
        if ss.endswith('A') and ss.startswith('B'):
            count_BA += 1
            continue
        if ss.endswith('A'):
            count_endswith_A += 1
        if ss.startswith('B'):
            count_startswith_B += 1
    count_pair = min(count_endswith_A, count_startswith_B)
    if count_pair > 0:
        print(count_AB + count_pair + count_BA)
    elif count_endswith_A > 0 or count_startswith_B > 0:
        print(count_AB + count_BA)
    elif count_BA > 0:
        print(count_AB + count_BA - 1)
    else:
        print(count_AB)
    return


