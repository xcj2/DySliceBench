#!/usr/bin/env python3
import sys, itertools

def eratosthenes_sieve(n: int):
    """
    エラトステネスの篩を用いてn以下の素数を求める
    """
    table = [0] * (n + 1)
    prime_list = [0, 0]
    
    for i in range(2, n + 1):
        if table[i] == 0:
            prime_list.append(1)
            for j in range(i + i, n + 1, i):
                table[j] = 1
        else:
            prime_list.append(0)
    
    return prime_list

def solve(Q: int, l: "List[int]", r: "List[int]"):
    A = [0] * 100002
    prime_list = eratosthenes_sieve(100001)
    for i, p in enumerate(prime_list):
        if p == 1 and i % 2 == 1 and prime_list[(i+1)//2] == 1:
            A[i] = 1
        else:
            A[i] = 0
    A = list(itertools.accumulate(A))
    for q in range(Q):
        ll = l[q]
        rr = r[q]
        print(A[rr] - A[ll-1])
    return


