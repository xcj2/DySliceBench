def primes(x):
    if x < 2: return []

    primes = [i for i in range(x)]
    primes[1] = 0 # 1は素数ではない

    # エラトステネスのふるい
    for prime in primes:
        if prime > math.sqrt(x): break
        if prime == 0: continue
        for non_prime in range(2 * prime, x, prime): primes[non_prime] = 0

    return set(prime for prime in primes if prime != 0)


def is_prime(prime_list,a):
    return a in prime_list

def solve(Q: int, L: "List[int]", R: "List[int]"):
    prime_list = primes(10**5)

    DP = [0] * (10**5)
    for i in range(1,int(10**5)):
        DP[i] = DP[i-1]
        if is_prime(prime_list,i) and is_prime(prime_list,(i+1)//2):
            DP[i] += 1

    for l,r in zip(L,R):
        print(DP[r] - DP[l-1])

