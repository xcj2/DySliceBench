import sys
import collections

def solve(N: int, M: int, A: "List[int]", B: "List[int]", C: "List[int]"):
    counter = collections.Counter(A)
    A = [[c, b] for c, b in counter.items()]
    for b, c in zip(B, C):
        A.append([c, b])

    A = sorted(A, reverse=True, key = lambda x:x[0])
    
    header = 0
    result = 0
    current_max = A[header]

    
    for i in range(N):
        if current_max[1] > 0:
            result += current_max[0]
            current_max[1] -= 1
        else:
            header += 1
            current_max = A[header]

            result += current_max[0]
            current_max[1] -= 1
    print(result)
    return


