#!/usr/bin/env python3
import sys
from itertools import product

def solve(N: int):
    nine = [9**i for i in range(5,0,-1)]
    six = [6**i for i in range(6,0,-1,)]
    answer = 10**6

    for six_bit in product([0,1,2,3,4,5],repeat = 6):
        tmp = 0
        for i in range(6):
            tmp += six[i]*six_bit[i]

        if tmp > N:
            continue
        
        count = sum(six_bit)
        cur = N-tmp
        for i in range(5):
            syou = cur//nine[i]
            cur%=nine[i]
            count += syou
        else:
            answer = min(answer,count+cur)
    print(answer)
    return


