    for i in range(N-1):
        adj[a[i]].append((b[i], c[i]))
        adj[b[i]].append((a[i], c[i]))

    D = [inf for i in range(N)]
    prev = [None for i in range(N)]
    D[K] = 0
    Queue = [K]
    while len(Queue) > 0:
        u = Queue.pop()
        for v, w in adj[u]:
            if v == prev[u]:
                continue
            prev[v] = u
            D[v] = D[u] + w
            Queue.append(v)
    
    for i in range(Q):
        print(D[x[i]] + D[y[i]])
    return


