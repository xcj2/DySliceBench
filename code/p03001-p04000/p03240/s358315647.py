#!/usr/bin/env python3
import sys

def sample_index_not_zero_in_all_h(h):
    for i in range(len(h)):
        if h[i] != 0:
            return i

def solve(N: int, x: "List[int]", y: "List[int]", h: "List[int]"):
    h_isnot_zero = sample_index_not_zero_in_all_h(h)
    for cx in range(0, 101):
        for cy in range(0, 101):
            # 仮の頂点(Cx, Cy)の高さHを設定
            H_is_true = True
            H = h[h_isnot_zero] + abs(x[h_isnot_zero] - cx) + abs(y[h_isnot_zero] - cy)
            for i in range(N):
                if max(H - abs(x[i] - cx) - abs(y[i] - cy) , 0) != h[i]:
                    H_is_true = False
                    break
            if H_is_true == True:
                print(cx, cy, H)
                return


