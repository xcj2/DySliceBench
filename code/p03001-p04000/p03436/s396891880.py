def bfs(graph,start,end):
    queue = [start]
    visited = {}
    visited[start[0],start[1]] = 1
    while queue:
        i,j = queue.pop(0)
        if (i,j) == end:
            return visited[i,j]
        for di,dj in [(1,0),(-1,0),(0,1),(0,-1)]:
            if 0 <= i+di < len(graph) and\
                0 <= j+dj < len(graph[0]) and\
                graph[i+di][j+dj] != "#" and\
                (i+di,j+dj) not in visited:
                visited[i+di,j+dj] = visited[i,j] + 1
                queue.append((i+di,j+dj))
    return -1

def get_black_cnt(graph):
    return(sum([s.count("#") for s in graph]))


