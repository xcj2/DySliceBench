#!/usr/bin/env python3
import sys
import heapq
from collections import deque


inf = float("inf")

def solve(N: int, a: "List[int]"):
    L = a[:N]
    R = [-x for x in a[2*N:]]
    heapq.heapify(L)
    heapq.heapify(R)
    M = a[N:2*N]
    sumL = [0 for _ in range(N+1)] # sumL[i]: a[0]からa[N-1+i]までの大きい順にN個の和
    sumR = [0 for _ in range(N+1)] # sumR[i]: -(a[N-1+i]からa[3*N-1]までの小さい順にN個の和)

    sumL[0] = sum(L)
    sumR[N] = sum(R)

    for i in range(N):
        l = heapq.heappop(L)
        diff = M[i] - l
        if diff > 0:
            sumL[i+1] = sumL[i] + diff
            heapq.heappush(L, M[i])
        else:
            sumL[i+1] = sumL[i]
            heapq.heappush(L, l)
    
    for i in range(N-1, -1, -1):
        r = heapq.heappop(R)
        diff = -M[i] - r
        if diff > 0:
            sumR[i] = sumR[i+1] + diff
            heapq.heappush(R, -M[i])
        else:
            sumR[i] = sumR[i+1]
            heapq.heappush(R, r)
    
    res = -inf
    for suml, sumr in zip(sumL, sumR):
        res = max(res, suml + sumr)
    print(res)
    return


