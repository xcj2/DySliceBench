import sys, math, fractions, itertools


def solve(N: int, M: int, a: "List[int]", b: "List[int]"):

    visited = [0] * N
    visited[0] = 1
    G = [[] for _ in range(N)]
    for i in range(M):
        G[a[i]-1].append(b[i]-1)
        G[b[i]-1].append(a[i]-1)

    def dfs(v):
        if all(visited):
            return 1
        else:
            counter = 0
            for g in G[v]:
                if visited[g]:
                    continue
                visited[g] = 1
                counter += dfs(g)
                visited[g] = 0
            return counter
    print(dfs(0))
    return


