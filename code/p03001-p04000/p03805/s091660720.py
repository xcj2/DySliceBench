import sys
import itertools


def solve(N: int, M: int, a: "List[int]", b: "List[int]"):

    paths = list(zip(a, b))

    permutations = []
    for permutation in itertools.permutations(range(1, N + 1)):
        if permutation[0] == 1:
            permutations.append(permutation)
        else:
            break
    # print(permutations)
    result = 0
    for permutation in permutations:
        able = True
        for i in range(N - 1):
            if (
                permutation[i : i + 1 + 1] in paths
                or tuple(reversed(list(permutation[i : i + 1 + 1]))) in paths
            ):
                pass
            else:
                able = False
                break

        if able:
            result += 1

    print(result)

    return


