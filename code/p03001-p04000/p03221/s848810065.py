def pf(s): return print(s, flush=True)


def main():
    n,m = LI()
    py = sorted([LI() + [i] for i in range(m)], key=lambda x: [x[1], x])
    d = collections.defaultdict(int)
    rd = {}
    for p,y,i in py:
        d[p] += 1
        rd[i] = '{:06d}{:06d}'.format(p,d[p])

    return '\n'.join(map(lambda x: rd[x], range(m)))


print(main())
