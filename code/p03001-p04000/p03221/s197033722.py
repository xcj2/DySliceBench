import sys
from itertools import *
from operator import itemgetter


def solve(N: int, M: int, P: "List[int]", Y: "List[int]"):
    items = [(P[i], Y[i]) for i in range(M)]

    key_to_value_to_rank = {}
    for key, sorted_items in groupby(sorted(items), key = itemgetter(0)):
        value_to_rank = dict((item, index + 1) for index, item in enumerate(map(lambda x: x[1], sorted_items)))
        key_to_value_to_rank[key] = value_to_rank

    for key, value in items:
        rank = key_to_value_to_rank[key][value]
        print('{0:06d}'.format(key, rank) + '{0:06d}'.format(rank))

    return


