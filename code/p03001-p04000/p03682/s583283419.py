from operator import itemgetter
N = int(input())
cities = []

for i in range(N):
    x, y = map(int, input().split())
    cities.append((i, x, y))


edge = []
for k in (itemgetter(1), itemgetter(2)):
    cities.sort(key=k)
    for j in range(N-1):
        d = min(abs(cities[j+1][1]-cities[j][1]),
                abs(cities[j+1][2]-cities[j][2]))
        edge.append((cities[j][0], cities[j+1][0], d))
edge.sort(key=itemgetter(2))


class UnionFind():
    # 作りたい要素数nで初期化
    # 使用するインスタンス変数の初期化
    def __init__(self, n):
        self.n = n
        # root[x]<0ならそのノードが根かつその値が木の要素数
        # rootノードでその木の要素数を記録する
        self.root = [-1]*(n+1)
        # 木をくっつける時にアンバランスにならないように調整する
        self.rnk = [0]*(n+1)

    # ノードxのrootノードを見つける
    def Find_Root(self, x):
        if(self.root[x] < 0):
            return x
        else:
            # ここで代入しておくことで、後の繰り返しを避ける
            self.root[x] = self.Find_Root(self.root[x])
            return self.root[x]
    # 木の併合、入力は併合したい各ノード

    def Unite(self, x, y):
        # 入力ノードのrootノードを見つける
        x = self.Find_Root(x)
        y = self.Find_Root(y)
        # すでに同じ木に属していた場合
        if(x == y):
            return
        # 違う木に属していた場合rnkを見てくっつける方を決める
        elif(self.rnk[x] > self.rnk[y]):
            self.root[x] += self.root[y]
            self.root[y] = x

        else:
            self.root[y] += self.root[x]
            self.root[x] = y
            # rnkが同じ（深さに差がない場合）は1増やす
            if(self.rnk[x] == self.rnk[y]):
                self.rnk[y] += 1
    # xとyが同じグループに属するか判断

    def isSameGroup(self, x, y):
        return self.Find_Root(x) == self.Find_Root(y)

    # ノードxが属する木のサイズを返す
    def Count(self, x):
        return -self.root[self.Find_Root(x)]


uf = UnionFind(N)

ans = 0
for e in edge:
    if not uf.isSameGroup(e[0], e[1]):
        ans += e[2]
        uf.Unite(e[0], e[1])
print(ans)
