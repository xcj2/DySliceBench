def solve_(N: int, A: "List[int]"):
    m = 1e10
    s = 0
    n_plus, n_minus = 0, 0
    for x in A:
        m = min(m, abs(x))
        if x >= 0:
            n_plus += 1
        else:
            n_minus += 1
        s += abs(x)
    # print(n_plus, n_minus)
    if n_minus % 2 == 0:
        print(s)
    else:
        print(s - m * 2)

    return


