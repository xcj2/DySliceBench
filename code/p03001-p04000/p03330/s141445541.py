import sys, math, fractions, itertools


def solve(N: int, C: int, D: "List[List[int]]", c: "List[List[int]]"):
    """
    (x+y)%3が等しければ色も等しいので良いグリッドには色は3色しかない。
    これを利用して30C3種類全探索。
    """
    t = [[0 for _ in range(30)] for _ in range(3)]
    for i in range(N):
        for j in range(N):
            t[(i+j)%3][c[i][j]-1] += 1

    res = 1 << 30
    for i in range(C):
        for j in range(C):
            if i != j:
                for k in range(C):
                    if i != k and j != k:
                        tt = 0
                        for l in range(C):
                            tt += D[l][i] * t[0][l]
                        for l in range(C):
                            tt += D[l][j] * t[1][l]
                        for l in range(C):
                            tt += D[l][k] * t[2][l]
                        if tt < res:
                            res = tt
    print(res)
    return


