#!/usr/bin/env python3
import sys
import itertools

inf = float('inf')

def solve(N: int, C: int, D: "List[List[int]]", c: "List[List[int]]"):
    num_count = [[0] * C for i in range(3)]
    for i in range(N):
        for j in range(N):
            num_count[(i+j)%3][c[i][j]] += 1
    
    diff_sum = [[0] * C for i in range(3)]
    for i in range(C):
        for j in range(C):
            for n in range(3):
                diff_sum[n][j] += D[i][j] * num_count[n][i]

    res = inf
    for i, j, k in itertools.permutations(range(C), 3):
        s = diff_sum[0][i] + diff_sum[1][j] + diff_sum[2][k]
        if s < res:
            res = s
    print(res)
    return


