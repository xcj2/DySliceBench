import sys, math, fractions, itertools, collections

MOD = 1000000007  # type: int

def mpow(n, base):
    res = 1
    for i in range(n):
        res = res * base % MOD
    return res

def solve(N: int, A: "List[int]"):
    A.sort()
    if N % 2 == 0:
        for i in range(0, N//2):
            if A[2*i] != 2*i+1 or A[2*i+1] != 2*i+1:
                print(0)
                return
        print(mpow(N//2, 2))
    else:
        for i in range(0, N//2):
            if i == 0:
                if A[0] != 0:
                    print(0)
                    return
                else:
                    continue
            if A[2*i] != 2*i or A[2*i-1] != 2*i:
                print(0)
                return
        print(mpow(N//2, 2))
    return


