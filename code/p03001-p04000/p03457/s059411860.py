import sys

YES = "Yes"  # type: str
NO = "No"  # type: str

def dist(a, b):
    dist = 0
    dist += abs(a[0] - b[0])
    dist += abs(a[1] - b[1])
    return dist

def solve(N: int, t: "List[int]", x: "List[int]", y: "List[int]"):
    txy = [[i, j, k] for i,j,k in zip(t, x, y)]
    txy = sorted(txy, key = lambda x: x[0])
    flag = 0
    coordinate_start = [0, 0]
    t_start = 0
    for t, x, y in txy:
        coordinate_goal = [x, y]
        time_to_travel = t - t_start
        distance = dist(coordinate_start, coordinate_goal)
        if distance > time_to_travel:
            flag = False
            break
        if distance <= time_to_travel:
            if (distance - time_to_travel) % 2 == 0:
                flag = True
            else:
                flag = False
                break
        t_start = t
        coordinate_start = [x, y]
    if flag == True:
        print(YES)
    else:
        print(NO)
    return


