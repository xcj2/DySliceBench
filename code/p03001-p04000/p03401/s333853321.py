import sys


def solve(N: int, A: "List[int]"):

    cost = abs(A[0]) + abs(A[-1])
    for i in range(1,len(A)):
        cost += abs(A[i-1]-A[i])

    for i in range(len(A)):
        cp = A[i]
        pp = 0
        np = 0
        if i>0:
            pp = A[i-1]
        if (i+1) < len(A):
            np = A[i+1]
                   
        if pp <= cp <= np or pp >= cp >= np:
            print(cost)
        elif np <= pp <= cp or cp <= pp <= np:
            print(cost - abs(pp-cp)*2)
        elif cp <= np <= pp or cp >= np >= pp:
            print(cost - abs(np-cp)*2)
        


