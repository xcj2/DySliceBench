#!/usr/bin/env python3
import sys


def solve(N: int):
    if N % 2 == 0:              # 偶数
        key = int(N/2)
        M = (N-2)*key
        print(M)
        for i in range(1, key+1):
            for j in range(i+1, N+1):
                if (j <= key) or\
                   (j > key and i % key != (N+1-j) % key):
                    print(i, j)
        for i in range(key+1, N):
            for j in range(i+1, N+1):
                print(i, j)
    else:
        key = int(N/2)
        M = (N-3)*key + N-1
        print(M)
        for i in range(1, key+1):
            for j in range(i+1, N+1):
                if (j <= key) or\
                   (j > key and i % key != (N-j) % key):
                    print(i, j)
                elif j == N:
                    print(i, j)
        for i in range(key+1, N):
            for j in range(i+1, N+1):
                print(i, j)
    return


