#!/usr/bin/env python3
import sys
from itertools import accumulate, product

# 各重さごとに価値降順でソート
# とっていく
# 重さ合計は w0 * k ~ (w0 + 3) * kのどれか N=100だと15000通りくらい

def solve(N: int, W: int, ws: "List[int]", vs: "List[int]"):
    w0 = ws[0]
    items = [[] for _ in range(4)]
    accum = [[] for _ in range(4)]
    for w, v in zip(ws, vs):
        items[w-w0].append(v)
    for i in range(4):
        items[i].sort(reverse=True)
        accum[i] = [0] + list(accumulate(items[i]))
    count = [len(items[i]) for i in range(4)]
    
    res = 0
    for nums in product(*[range(count[i] + 1) for i in range(4)]):
        w = sum((w0+i) * nums[i] for i in range(4))
        if w > W:
            continue
        v = sum(accum[i][nums[i]] for i in range(4))
        res = max(v, res)
    
    print(res)
    return


