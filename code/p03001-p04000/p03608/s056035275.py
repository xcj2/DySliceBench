    G = [[INF for _ in range(N)] for _ in range(N)]
    for i in range(M):
        G[A[i]-1][B[i]-1] = C[i]
        G[B[i]-1][A[i]-1] = C[i]
    cost = WarshallFloyd(N, G)
    mn = 1e18
    for p in itertools.permutations(r):
        path = 0
        for i in range(R-1):
            path += cost[p[i+1]-1][p[i]-1]
        mn = min(path, mn)
    print(mn)
    return


