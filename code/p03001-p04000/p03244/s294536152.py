#!/usr/bin/env python3
import sys
import collections


def solve(n: int, V: "List[int]"):

    ev = V[0::2]
    ov = V[1::2]

    ec = collections.Counter(ev)
    oc = collections.Counter(ov)

    em = ec.most_common()
    om = oc.most_common()

    if em[0][0] != om[0][0]:
        print( n-em[0][1]-om[0][1])
    else:
        if len(em) == 1 and len(om) == 1:
            print(n-em[0][1])
        elif  len(em) == 1:
            print( n-em[0][1]-om[1][1])
        elif  len(om) == 1:
            print( n-em[1][1]-om[0][1])
        else:
            print(min(n-em[0][1]-om[1][1], n-em[1][1]-om[0][1]))

            



