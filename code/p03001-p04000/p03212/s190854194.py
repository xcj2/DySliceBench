#!/usr/bin/env python3
import sys
import itertools

def solve(N: int):
    n = len(str(N))
    ans = 0
    candidate = ["3", "5", "7"]
    break_flag = False
    for i in range(1, n + 1):
        combi_int = []
        for tmp in itertools.product(candidate, repeat=i):
            combi_int.append(int("".join(tmp)))
        combi_int = sorted(combi_int)
        if break_flag:
            break
        for tmp in combi_int:
            if N < tmp:
                break_flag = True
                break
            else:
                if "3" in str(tmp) and "5" in str(tmp) and "7" in str(tmp):
                    #print(tmp)
                    ans += 1
    print(ans)

