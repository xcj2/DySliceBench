#!/usr/bin/env python3
import sys


def solve(A: int, B: int, C: int, X: int, Y: int):
    ans = 10**9
    if Y > X:
        bigger_y = 1
        bigger_x = 0
    elif Y == X:
        bigger_y = 1
        bigger_x = 1
    else:
        bigger_y = 0
        bigger_x = 1

    if A + B < 2 * C:#C=0
        ans = A*X + B*Y
    else:#C>1
        #Aを2*Cで補うときの利益 > Bを2*Cで補うときの利益
        if A*X - 2*C*X + B*(Y-X)*bigger_y > B*Y - 2*C*Y + A*(X-Y)*bigger_x:
            #A=0
            if bigger_x:
                ans = 2*C*X
            else:
                ans = 2*C*X + (Y-X)*B

        #Aを2*Cで補うときの利益 <= Bを2*Cで補うときの利益
        else:
            #B=0
            if bigger_y:
                ans = 2*C*Y
            else:
                ans = 2*C*Y + (X-Y)*A
        if 2*C < A and 2*C < B:
            ans = min(ans, 2*C*max(X,Y))
    print(ans)

