#!/usr/bin/env python
import sys


def solve(H: int, W: int, S: "List[str]"):
    def isBlock(x, y):
        return S[y][x] == "#"
    cacheW = [[0 for i in range(W)] for j in range(H)]
    cacheH = [[0 for i in range(W)] for j in range(H)]
    for i in range(H):
        count = 0
        begin = 0
        for j in range(W):
            if isBlock(j, i):
                for k in range(begin, j):
                    cacheW[i][k] = count
                begin = j+1
                count = 0
            else:
                count += 1
        if begin != W:
            for k in range(begin, W):
                cacheW[i][k] = count
    for i2 in range(W):
        count2 = 0
        begin2 = 0
        for j2 in range(H):
            if isBlock(i2, j2):
                for k2 in range(begin2, j2):
                    cacheH[k2][i2] = count2
                # print("x="+str(i2) +"--"+ str(begin2)+"~"+str(j2)+"::"+str(count2))
                begin2 = j2+1
                count2 = 0
            else:
                count2 += 1
        if begin2 != H:
            for k in range(begin2,H):
                cacheH[k][i2] = count2
    m = 0
    # print(cacheW)
    # print(cacheH)
    for i in range(W):
        for j in range(H):
            c = cacheW[j][i] + cacheH[j][i]-1
            m = max(m, c)
            # print(str(i)+"-"+str(j)+":"+str(c))
    print(m)
    return


