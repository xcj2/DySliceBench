import sys
import itertools
import math


def solve(D: int, G: int, p: "List[int]", c: "List[int]"):

    cpl = [ (i+1)*100*pp+cc for i,(pp,cc) in enumerate(zip(p,c)) ]

    min_n = float("inf")
    for tfl in itertools.product([True,False],repeat=D):
        cmp_total_n = sum(itertools.compress(p,tfl))
        cmp_total_p = sum(itertools.compress(cpl,tfl))
        if cmp_total_p < G:
            ntfl = [ not i for i in tfl ]
            max_i = max(itertools.compress([i for i in range(0,D)],ntfl))
            max_ip = 100*(max_i+1)

            additinal_n = int(math.ceil((G-cmp_total_p)/max_ip))
            if additinal_n < p[max_i]:
                min_n = min(min_n,cmp_total_n+additinal_n)
        else:
            min_n = min(min_n, cmp_total_n)

    print(min_n)



