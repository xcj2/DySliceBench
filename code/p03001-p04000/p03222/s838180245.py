#!/usr/bin/env python3
import sys

MOD = 1000000007  # type: int

def solve(H: int, W: int, K: int):
    # t[h][k]: h x W のあみだくじのうち, k+1本目にたどり着くパターンの総数
    t = [[0 for i in range(W)] for j in range(H+1)]
    t[0][0] = 1
    
    # d[w]: 縦w本のあみだくじに線をひくパターンの総数
    d = [0 for i in range(W+1)]
    d[0] = 1
    d[1] = 1
    for w in range(2, W+1):
        d[w] += d[w-1] #一番右に線を引かない場合
        d[w] += d[w-2] #一番右に線を引く場合

    for h in range(1, H+1):
        for k in range(W):
            if k > 0:
                # 左からくるパターン -*
                t[h][k] += t[h-1][k-1] * d[k-1] * d[W-k-1]
                t[h][k] %= MOD
            if k < W-1:
                # 右からくるパターン *-
                t[h][k] += t[h-1][k+1] * d[k] * d[W-k-2]
                t[h][k] %= MOD
            # 上からくるパターン ..
            t[h][k] += t[h-1][k] * d[k] * d[W-k-1]
            t[h][k] %= MOD

    print(t[H][K-1])
    return


