#!/usr/bin/env python3
import sys

MOD = 1000000007  # type: int

def solve(N: int):
    dp = [[[[0 for _ in range(4)] for _ in range(4)] for _ in range(4)] for _ in range(N+1)]
    # A:0, G:1, C:2, T:3
    chars = ['A', 'G', 'C', 'T']
    for i in range(4):
        for j in range(4):
            for k in range(4):
                dp[3][i][j][k] = 1
    dp[3][0][1][2] = 0
    dp[3][0][2][1] = 0
    dp[3][1][0][2] = 0
    cnt = 0
    for i in range(3, N):
        for j1, c1 in enumerate(chars):
            for j2, c2 in enumerate(chars):
                for j3, c3 in enumerate(chars):
                    for j4, c4 in enumerate(chars):
                        cs4 = c1+c2+c3+c4
                        cs3 = c2+c3+c4
                        if 'AGC'==cs3 or 'ACG'==cs3 or 'GAC'==cs3 or 'AAGC'==cs4 or 'ACGC'==cs4 or 'AGGC'==cs4 or 'ATGC'==cs4 or 'AGAC'==cs4 or 'AGGC'==cs4 or 'AGCC'==cs4 or 'AGTC'==cs4:
                            continue
                        cnt += 1
                        dp[i+1][j2][j3][j4] += dp[i][j1][j2][j3]
                        dp[i+1][j2][j3][j4] %= MOD
    ans = 0
    for i in range(4):
        for j in range(4):
            for k in range(4):
                ans += dp[N][i][j][k]
                ans %= MOD
    print(ans)

    return


