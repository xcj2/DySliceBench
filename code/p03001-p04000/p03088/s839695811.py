#!/usr/bin/env python3
import sys, math, fractions, itertools

MOD = 1000000007  # type: int
memo = []

def ok(last4: str):
    for i in range(4):
        t = list(last4)
        if i >= 1:
            t[i-1], t[i] = t[i], t[i-1]
        if ''.join(t).count('AGC') >= 1:
            return False
    return True

def dfs(N: int, cur: int, last3: str):
    if last3 in memo[cur]:
        return memo[cur][last3]
    if cur == N:
        return 1
    ret  = 0
    for c in 'ACGT':
        if ok(last3 + c):
            ret = (ret + dfs(N, cur+1, last3[1:] + c)) % MOD
    memo[cur][last3] = ret
    return ret

def solve(N: int):
    print(dfs(N, 0, 'TTT'))
    return


