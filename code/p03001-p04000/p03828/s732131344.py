#!/usr/bin/env python3
import sys, math, fractions, itertools

MOD = 1000000007  # type: int

def is_prime(n):
    if n == 1: return False

    for k in range(2, int(math.sqrt(n)) + 1):
        if n % k == 0:
            return False

    return True

def solve(N: int):
    primes = [n for n in range(1, N+1) if is_prime(n)]
    counter = [0] * len(primes)
    for n in range(2, N+1):
        for i, p in enumerate(primes):
            mod = 0
            c = 0
            r = n
            while(mod == 0):
                mod = r % p
                r /= p
                if mod == 0:
                    c += 1
            counter[i] += c
    res = 1
    for c in counter:
        res *= (c+1)
        res %= MOD
    print(res)
    return 


