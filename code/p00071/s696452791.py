import sys


def check_bombs(map, pos, dir, range=3):
    """
    ????¢¨????±???????????????\??????????????????????????§???????????????
    (?????°????????????????¢¨????±??????´?????§????????????????????????????????????????????§????????????????????????)
    :param map: ?????¨?????¶???
    :param pos: ???????????????????????????
    :param dir: ?????§????????????????¢¨????????? (up, down, left, right)
    :param range: ????¢¨????±??????????
    :return: ???????????????????????????????????? or None
    """
    if dir == 'up':
        x, y = pos
        while range > 0 and y > 0:
            if map[y-1][x] == '1':
                return (x, y-1)
            else:
                y -= 1
                range -= 1
    elif dir == 'down':
        x, y = pos
        while range > 0 and y < len(map)-1:
            if map[y+1][x] == '1':
                return (x, y+1)
            else:
                y += 1
                range -= 1
    elif dir == 'left':
        x, y = pos
        while range > 0 and x > 0:
            if map[y][x-1] == '1':
                return (x-1, y)
            else:
                x -= 1
                range -= 1
    elif dir == 'right':
        x, y = pos
        while range > 0 and x < len(map[0])-1:
            if map[y][x+1] == '1':
                return (x+1, y)
            else:
                x += 1
                range -= 1
    else:
        return None


def chain_bombs(map, init_pos):
    """
    ???????????£?????????????????¶???????¨??????????
    :param map: ???????????????????????¶???
    :param init_pos: (0, 0)?????????????????????????????????????????????????????§?¨?
    :return: ??????????????????????????¶???
    """
    lmap = map[:]               #  ??????????????¶????¨??????¨
    detonated = [init_pos]      #  ??±?????????????????????????????????(????????????)
    while detonated:
        x, y = detonated.pop()
        lmap[y][x] = '0'
        res = check_bombs(lmap, (x, y), 'up')
        if res:
            detonated.append(res)
        res = check_bombs(lmap, (x, y), 'down')
        if res:
            detonated.append(res)
        res = check_bombs(lmap, (x, y), 'left')
        if res:
            detonated.append(res)
        res = check_bombs(lmap, (x, y), 'right')
        if res:
            detonated.append(res)
    return lmap


def main(args):
    data_set = int(input())
