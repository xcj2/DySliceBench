def dfs(hand, count):
    # ??¢??????n????????£??????????????¨????¢??????????
    if count < 1:
        return True

    for i, n in enumerate(hand[1:], start=1):
        if n == 0:
            continue
        if n >= 3:
            c_hand = hand[:]
            c_hand[i] -= 3
            res = dfs(c_hand[:], count-1)
            if res:
                return True
        if i > 7:
            return False
        if hand[i+1] >= 1 and hand[i+2] >= 1:
            c_hand = hand[:]
            c_hand[i] -= 1
            c_hand[i+1] -= 1
            c_hand[i+2] -= 1
            res = dfs(c_hand[:], count-1)
            if res:
                return True
        else:
            return False


