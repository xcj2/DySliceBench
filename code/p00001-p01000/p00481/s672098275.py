def bfs(field, sx, sy, gx, gy):
    """
    ??????????????°???????????´????????°????????§????????¢????±???????
    :param field:
    :param sx: ??????????????°????????§?¨?
    :param sy:
    :param gx: ??´????????°????????§?¨?
    :param gy:
    :return: ????????????????????´???????????§????????¢
    """
    # ????????????????§????????????´????????§?¨?????????????
    dy = [-1, 1, 0, 0]
    dx = [0, 0, -1, 1]

    # ??°???????????????(?§????????????£????????????????????????????????§??????????????¨)
    Y = len(field)
    X = len(field[0])
    # d = [[float('inf')] * X for _ in range(Y)] #  ??????????????°?????????????????¢???INF??§?????????
    d = defaultdict(int)

    # ???????????????????????????????????°???????????´????????°????????§????????¢????±???????
    Q = deque()
    Q.append((sx, sy))
    d['{:04d}{:04d}'.format(sy, sx)] = 0               #  ??????????????°??????????????????0
    while Q:
        cx, cy = Q.popleft()        #  ?????¨??°?????§?¨?
        if cx == gx and cy == gy:
            break
        for i in range(4):
            nx = cx + dx[i]
            ny = cy + dy[i]
            # ?§?????????? ??°????????????????????????????????? and ?£?????????£???????????? and ??¢?????¢?´¢?????§?????? ??´???
            if (0 <= nx < X) and (0 <= ny < Y) and field[ny][nx] != 'X' and '{:04d}{:04d}'.format(ny, nx) not in d:
                Q.append((nx, ny))
                d['{:04d}{:04d}'.format(ny, nx)] = d['{:04d}{:04d}'.format(cy, cx)] + 1
    return d['{:04d}{:04d}'.format(gy, gx)]


def solve(field, N):
    # ??????????????°???(S)??¨??´????????°???(N)?????????
    pos = [[None, None] for _ in range(N+1)]
    for y, row in enumerate(field):
        for mark in 'S123456789':
            if mark in row:
                if mark == 'S':
                    pos[0] = [row.index(mark), y]
                else:
                    pos[int(mark)] = [row.index(mark), y]

    total_move = 0
    start = pos[0]
    for goal in pos[1:]:
        sx, sy = start
        gx, gy = goal
        res = bfs(field, sx, sy, gx, gy)
        # print('From: ({}, {}) -> To: ({}, {}), step: {}'.format(sx, sy, gx, gy, res))
        # print('min move: {}'.format(abs(sx-gx) + abs(sy-gy)))
        total_move += res
        start = goal

    return total_move


