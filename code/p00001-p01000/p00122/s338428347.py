import sys
from sys import stdin
from collections import namedtuple, deque
input = stdin.readline


def bfs(pyon, sprinklers):
    # ??´?????????????§????????????´????????§?¨??????????
    # ??? ?§?????????????(0, 0)??¨??????????????¢?????\???????????????
    dy = [-2, -2, -2, -1,  0,  1, -1, 0, 1,  2, 2, 2]
    dx = [-1,  0,  1, -2, -2, -2,  2, 2, 2, -1, 0, 1]

    # ??????????????°???(S)
    sx = pyon.x                 #  ??????????????°????????§?¨?
    sy = pyon.y
    num_sprinkler = len(sprinklers)
    jump = 0                    #  ?????£?????????????????°

    Q = deque()
    Q.append((sx, sy, jump))    #  ????????????????????????????????????????????°?????????????????§????????¨????????????????????????????????£?????????????¨???¶????????????
    while Q:
        cx, cy, jump = Q.popleft()        #  ?????¨??°?????§?¨?
        if jump >= num_sprinkler:         #  ???????????????????????????????????????????????????????????§?????????????????¨?????§?????????????????¶?????????????????????????????????????????????????????????OK???????
            return 'OK'
        for i in range(len(dx)):
            nx = cx + dx[i]
            ny = cy + dy[i]
            #  ?§?????????§?????????????????¨?????§????????°?????????????????¢?´¢????¶??????????????????\????????\????????????
            if is_safe(sprinklers, jump, nx, ny):
                Q.append((nx, ny, jump + 1))
    return 'NA'


def is_safe(sprinklers, jump, nx, ny):
    # ?????£????????????????????¬???????????°?????§?????????????????????????°´????±??????????????¢??????????
    if not 0 <= nx <= 9:
        return False
    if not 0 <= ny <= 9:
        return False
    sp_x = sprinklers[jump].x
    sp_y = sprinklers[jump].y
    if not sp_x - 1 <= nx <= sp_x + 1:
        return False
    if not sp_y - 1 <= ny <= sp_y + 1:
        return False
    return True


def can_survive(pyon, sprinklers):
    return bfs(pyon, sprinklers)


pos = namedtuple('pos', ['x', 'y'])
def main(args):
    while True:
        px, py = map(int, input().split()) #  ??´????????????????????????
        if px == 0 and py == 0:
            break
        pyon = pos(px, py)
        n = int(input())        #  ??????????????????????????°
        temp = [int(x) for x in input().split(' ')]
        sprinklers = []         #  ??????????????????????????§?¨?
        for i in range(n):
            sprinklers.append(pos(temp[i*2], temp[i*2+1]))

        result = can_survive(pyon, sprinklers)
        print(result)


if __name__ == '__main__':
    main(sys.argv[1:])
    