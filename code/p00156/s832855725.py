def solve(field):
    # ??????????????°???(????????£: &)?????????
    start = (0, 0)
    for y, row in enumerate(field):
        if '&' in row:
            start = (row.index('&'), y)

    sx, sy = start
    climb = 0                   #  ???????????????????????° = ??????????????????????????°
    while True:
        res, moats = bfs(field, sx, sy) #  ????????£????????°?????????????????????????¢????
        if res is False:
            climb += 1
            fill_moat(field, moats) #  ??¢??\?????????????????????
        else:
            break
    return climb


