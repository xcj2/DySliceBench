import sys
from collections import deque

YES = "Yes"  # type: str

class Room:
    def __init__(self,index):
        self.index = index
        self.nPath = -1
        self.refs = []

    def connect(self,ref):
        self.refs.append(ref)
        ref.refs.append(self)

    def recSolve(self,queue):
        for r in self.refs:
            if r.nPath == -1:
                queue.append()

    def __str__(self):
        c = ""
        for r in self.refs:
            c += f"{r.index},"
        return f"{self.index}->{c} ({self.nPath})"

def solve(N: int, M: int, A: "List[int]", B: "List[int]"):
    rooms = [Room(i) for i in range(N)]
    for j in range(M):
        rooms[A[j]-1].connect(rooms[B[j]-1])
    current = deque()
    current.append((rooms[0],0))
    while len(current) > 0:
        next = deque()
        for r in current:
            if r[0].nPath == -1:
                r[0].nPath = r[1]
                for k in r[0].refs:
                    if k.nPath == -1:
                        next.append((k,r[0].index))
        current = next
