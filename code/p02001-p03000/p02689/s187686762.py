#!/usr/bin/env python3
import sys

class Node:
    def __init__(self,index,height):
        self.index = index
        self.height = height
        self.refs = []
        self.isGood = True

    def append(self,target):
        if target.height >= self.height:
            self.isGood = False
        if self.height >= target.height:
            target.isGood = False
        self.refs.append(target)
        target.refs.append(self)

def solve(N: int, M: int, H: "List[int]", A: "List[int]", B: "List[int]"):
    nodes = [Node(i,H[i]) for i in range(N)]
    for i in range(M):
        nodes[A[i]-1].append(nodes[B[i]-1])
    def isGood(node):
        return node.isGood

    print(len(list(filter(isGood,nodes))))
    return


