    A = sorted(A, reverse=True)
    m = 0
    while m < M:
        m += 1
        A[0] = A[0] // 2
        while m < M and len(A) > m and A[0] > A[M-m-1]:
            m += 1
            A[0] = A[0] // 2

        if (len(A) >= 2) and (A[0] < A[1]):
            tmp = A[0]
            A = A[1:]
            for i, a in enumerate(A):
                if a <= tmp:
                    A.insert(i, tmp)
                    break
                if i == len(A)-1:
                    A.insert(len(A)-1, tmp)
                    break
    print(sum(A))
    return




