#!/usr/bin/env python3
import sys
import heapq

def solve(N: int, M: int, A: "List[int]"):
    A = [-a for a in A]
    heapq.heapify(A)
    for m in range(M):
        largest = -1 * heapq.heappop(A)
        largest = int(largest / 2)
        heapq.heappush(A, -1 * largest)

    print(-1 * sum(A))
    return

