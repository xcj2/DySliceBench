def solve(H: int, W: int, M: int, h: "List[int]", w: "List[int]"):
    from collections import defaultdict
    h = [hh - 1 for hh in h]
    w = [ww - 1 for ww in w]
    row_values, col_values = [0] * H, [0] * W
    for hh, ww in zip(h, w):
        row_values[hh] += 1
        col_values[ww] += 1
    max_row_value = max(row_values)
    max_col_value = max(col_values)
    max_rows = set(filter(lambda i: row_values[i] == max_row_value, range(H)))
    max_cols = set(filter(lambda i: col_values[i] == max_col_value, range(W)))
    intersections = defaultdict(set) # intersections[col]
    for hh, ww in zip(h, w):
        if ww not in max_cols:
            continue
        if hh not in max_rows:
            continue
        intersections[ww].add(hh)
    m = min([len(intersections[col]) for col in max_cols])
    return max_row_value + max_col_value - (1 if m == len(max_rows) else 0)

