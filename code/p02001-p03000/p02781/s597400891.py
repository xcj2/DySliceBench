#!/usr/bin/env python3
import sys


def solve(N: "List[int]", K: int):
    print(dfs(N, False, 0, K, 0))


def dfs(N: "List[int]", f: bool, num: int, K: int, idx: int):
    if num == K:
        return 1
    if K - num > len(N) - idx:
        return 0
    else:
        if f:
            return dfs(N, True, num, K, idx + 1) + dfs(N, True, num + 1, K, idx + 1) * 9
        else:
            s = 0
            for i in range(N[idx] + 1):
                if i == N[idx]:
                    if i == 0:
                        s += dfs(N, False, num, K, idx + 1)
                    else:
                        s += dfs(N, False, num + 1, K, idx + 1)
                else:
                    if i == 0:
                        s += dfs(N, True, num, K, idx + 1)
                    else:
                        s += dfs(N, True, num + 1, K, idx + 1)
            return s


