#!/usr/bin/env python3
import sys


def solve(N: int, X: "List[int]", L: "List[int]"):
    d = {}
    for i in range(N):
        d[X[i]]=L[i]

    d=sorted(d.items())


    toru1=0
    maeR=d[0][0]+d[0][1]
    for i in range(1,N):
        tsugiL=d[i][0]-d[i][1]
        if maeR>tsugiL:
            tsugiR=d[i][0]+d[i][1]
            toru1+=1
            if tsugiR<maeR:
                maeR=tsugiR
        else:
            maeR=d[i][0]+d[i][1]

    toru2=0
    maeL=d[N-1][0]-d[N-1][1]
    for i in reversed(range(N-1)):
        tsugiR=d[i][0]+d[i][1]
        if maeL<tsugiR:
            tsugiL=d[i][0]-d[i][1]
            toru2+=1
            if tsugiL<maeR:
                maeR=tsugiL
            toru2+=1
        else:
            maeL=d[i][0]-d[i][1]

    print(N-min(toru1,toru2))
    
    return


