#!/usr/bin/env python3
import sys


def solve(N: int, S: str):
    C = [[0 for i in range(3)] for j in range(N+1)]
    for i in range(N-1,-1,-1):
        if S[i] == "R":
            C[i][0] = C[i+1][0]+1
            C[i][1] = C[i+1][1]
            C[i][2] = C[i + 1][2]
        elif S[i] == "G":
            C[i][0] = C[i + 1][0]
            C[i][1] = C[i + 1][1]+1
            C[i][2] = C[i + 1][2]
        else:
            C[i][0] = C[i + 1][0]
            C[i][1] = C[i + 1][1]
            C[i][2] = C[i + 1][2]+1
    sum = 0
    # print(S)
    for i in range(N):
        for j in range(i+1,N-1):
            if S[i] == S[j]:
                continue
            k = j - i + j
            # 残りがRである場合
            if S[i] != "R" and S[j] != "R":
                sum += C[j+1][0]
                if k < N and S[k] == "R":
                    sum -=1
                # print(f"GB:{i},{j},Rp:{C[j + 1][0]}")
            if S[i] != "G" and S[j] != "G":
                sum += C[j + 1][1]
                if k < N and S[k] == "G":
                    sum -= 1
                # print(f"RB:{i},{j},Gp:{C[j + 1][1]}")
            if S[i] != "B" and S[j] != "B":
                sum += C[j + 1][2]
                if k < N and S[k] == "B":
                    sum -= 1
                # print(f"RG:{i},{j},RB:{C[j + 1][2]}")
    print(sum)
    return


