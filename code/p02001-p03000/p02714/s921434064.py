#!/usr/bin/env python3
import sys


def solve(N: int, S: str):
    R = set()
    G = set()
    B = set()
    for i in range(N):
        if S[i] == 'R':
            R.add(i)
        elif S[i] == 'G':
            G.add(i)
        else:
            B.add(i)
    
    d = 0
    for r in R:
        for g in G:
            x = min(r, g)
            y = max(r, g)
            if (2 * y - x) in B:
                d += 1
            if (2 * x - y) >= 0 and (2 * x - y) in B:
                d += 1
            if (y + x) / 2 == int((y + x) / 2) and (y + x) / 2 in B:
                d += 1
    print(len(R) * len(G) * len(B) - d)
    return


