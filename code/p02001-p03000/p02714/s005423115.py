#!/usr/bin/env python3
import sys


def solve(N: int, S: str):
    R = [0] * N
    G = [0] * N
    B = [0] * N
    for i, s in enumerate(S):
        if s == 'R':
            if i == 0:
                R[i] += 1
            else:
                R[i] += R[i-1] + 1
        else:
            if i == 0:
                R[i] == 0
            else:
                R[i] += R[i-1]
        if s == 'G':
            if i == 0:
                G[i] += 1
            else:
                G[i] += G[i-1] + 1
        else:
            if i == 0:
                G[i] == 0
            else:
                G[i] += G[i-1]
        if s == 'B':
            if i == 0:
                B[i] += 1
            else:
                B[i] += B[i-1] + 1
        else:
            if i == 0:
                B[i] == 0
            else:
                B[i] += B[i-1]
    counter = 0
    d = {'R': R, 'G': G, "B": B}
    for i in range(N):
        for j in range(N-1, i+1, -1):
            if S[i] == S[j]:
                continue
            l = ['R', 'G', 'B']
            l.remove(S[i])
            l.remove(S[j])
            L = d[l[0]]
            counter += L[j] - L[i]
            if (j-i) % 2 == 0 and S[(j+i)//2] == l[0]:
                counter -= 1
    print(counter)
    return


