import sys


def solve(N: int, a: "List[int]", b: "List[int]"):
    G = [[] for _ in range(N)]
    for i in range(N-1):
        G[a[i]-1].append(b[i]-1)
        G[b[i]-1].append(a[i]-1)
    T = dict()
    for i in range(N-1):
        T[(a[i]-1, b[i]-1)] = i
        T[(b[i]-1, a[i]-1)] = i
    q = [0]
    cn = max([len(g) for g in G])
    visited = [False] * N
    C = [0] * (N-1)
    while len(q) > 0:
        p = q.pop()
        visited[p] = True
        adj = G[p]
        v = None
        for a in adj:
            if visited[a]:
                v = a
        if v != None:
            ex = C[T[(v, p)]]
        else:
            ex = -1
        counter = 1
        for a in adj:
            if counter == ex:
                counter += 1
            if a != v:
                j = T[(a, p)]
                C[j] = counter
                counter += 1
        for a in adj:
            if not visited[a]:
                q.append(a)
    print(cn)
    for c in C:
        print(c)
    return


