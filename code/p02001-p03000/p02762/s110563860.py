#!/usr/bin/env python3
import sys
import collections


def solve(N: int, M: int, K: int, A: "List[int]", B: "List[int]", C: "List[int]", D: "List[int]"):
    par = list(range(N))
    rank = [0] * N

    def find(x):
        if par[x] == x:
            return x
        par[x] = find(par[x])
        return par[x]

    def unite(x, y):
        x = find(x)
        y = find(y)
        if x == y:
            return

        if rank[x] < rank[y]:
            par[x] = y
        else:
            par[y] = x
            if rank[x] == rank[y]:
                rank[x] += 1

    def same(x, y):
        return find(x) == find(y)

    friend = collections.defaultdict(set)
    for i in range(M):
        a = A[i] - 1
        b = B[i] - 1
        unite(a, b)
        friend[a].add(b)
        friend[b].add(a)

    block = collections.defaultdict(set)
    for i in range(K):
        c = C[i] - 1
        d = D[i] - 1
        block[c].add(d)
        block[d].add(c)

    tomodatinowa = [0] * N
    for i in range(N):
        tomodatinowa[find(i)] += 1

    res = [0] * N
    for i in range(N):
        res[i] = tomodatinowa[par[i]] - 1
        for bl in block[i]:
            if same(i, bl):
                res[i] -= 1
        for fr in friend[i]:
            if same(i, fr):
                res[i] -= 1

    print(" ".join(str(a) for a in res))
    return


