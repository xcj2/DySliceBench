def error_print(*args):
    print(*args, file=sys.stderr)


def mt(f):
    import time

    def wrap(*args, **kwargs):
        s = time.time()
        ret = f(*args, **kwargs)
        e = time.time()

        error_print(e - s, 'sec')
        return ret

    return wrap


@mt
def slv(N, K, A):
    b = [0] * N
    for a in A:
        for i in a:
            b[i-1] += 1
    return b.count(0)


def main():
    N, K = read_int_n()
    A = []
    for _ in range(K):
        read_int()
        A.append(read_int_n())
    print(slv(N, K, A))


if __name__ == '__main__':
    main()
