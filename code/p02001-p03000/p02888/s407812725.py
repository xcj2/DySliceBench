def main():
    n = I()
    l = sorted(LI())
    r = 0
    for i in range(n):
        k = i + 1
        li = l[i]
        for j in range(i+1,n):
            ij = li + l[j]
            while k < n-1 and l[k+1] < ij:
                k += 1
            r += k - j

    return r


print(main())

