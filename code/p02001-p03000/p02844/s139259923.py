#!/usr/bin/env python3
import sys

def solve(N: int, S: str):
    def nx(S):
        res = [[N+1] * 10 for _ in range(N+1)]
        for i in range(N-1, -1, -1):
            for j in range(10):
                res[i][j] = res[i+1][j]
            res[i][int(S[i])] = i
        return res
    dp = [[0] * 3 for _ in range(N+1)]
    dp[1] = [1, 0, 0]
    res = nx(S)
    for i in range(0, N+1):
        for j in range(10):
            if res[i][j] >= N: continue
            if res[0][j] == res[i][j]:
                dp[res[i][j]+1][0] = 1
            dp[res[i][j]+1][1] += dp[i][0]
            dp[res[i][j]+1][2] += dp[i][1]
    res = 0
    for i in range(N+1):
        res += dp[i][2]
    print(res)
    return


