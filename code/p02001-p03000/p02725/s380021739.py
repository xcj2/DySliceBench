def _left(K, A):
    rev_a = list(A[::-1])
    end = A[0] + K - A[len(A) - 1]
    left = np.ediff1d(np.array(rev_a), to_end=[end]).tolist()
    left = [abs(l) for l in left]
    return left


def _right(K, A):
    end = A[0] + K - A[len(A) - 1]
    right = np.ediff1d(np.array(A), to_end=[end]).tolist()
    return right


