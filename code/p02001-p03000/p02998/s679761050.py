#!/usr/bin/env python3
import sys
from collections import defaultdict
from collections import deque


def solve(N: int, X: "List[int]", Y: "List[int]"):
    adj = defaultdict(list)
    done = set()
    for x, y in zip(X, Y):
        xnode = (x, 0)
        ynode = (y, 1)
        adj[xnode].append(ynode)
        adj[ynode].append(xnode)

    points_to_add = 0    
    for x, y in zip(X, Y):
        xnode = (x, 0)
        ynode = (y, 1)
        if xnode in done or ynode in done:
            continue
        x_count = 1
        y_count = 0
        done.add(xnode)
        Q = deque()
        Q.append(xnode)
        while len(Q) > 0:
            node = Q.pop()
            for node_next in adj[node]:
                if node_next in done:
                    continue
                if node_next[1] == 0:
                    x_count += 1
                else:
                    y_count += 1
                Q.append(node_next)
                done.add(node_next)
        points_to_add += x_count * y_count
    print(points_to_add - N)
        
    return


