#!/usr/bin/env python3
import sys
sys.setrecursionlimit(10**6)
count = 0


def solve(K: int):

    def cDfs(prev, prevDigit, remainDigit):
        global count
        if remainDigit == 0:
            count += 1
            if count == K:
                print(prev)
                exit()
            # print(prev)
            return
        else:
            if prevDigit == 0:
                cDfs(prev*10, prevDigit, remainDigit-1)
                cDfs(prev*10+1, 1, remainDigit-1)
            elif prevDigit == 9:
                cDfs(prev*10+8, 8, remainDigit-1)
                cDfs(prev*10+9, prevDigit, remainDigit-1)
            else:
                a = (prevDigit+1) % 10
                b = (prevDigit-1) % 10
                MIN = min(a, b)
                MAX = max(a, b)
                cDfs(prev*10+MIN, MIN, remainDigit-1)
                cDfs(prev*10+prevDigit, prevDigit, remainDigit-1)
                cDfs(prev*10+MAX, MAX, remainDigit-1)
    for i in range(0, 100):
        for j in range(1, 10):
            cDfs(j, j, i)
    return


