    for i in range(N):
        if A[i] >= B[i]:
            counter += B[i]
            A[i] -= B[i]
            B[i] = 0
        else:
            counter += A[i]
            B[i] -= A[i]
            A[i] = 0
            if A[i+1] >= B[i]:
                counter += B[i]
                A[i+1] -= B[i]
                B[i] = 0
            else:
                counter += A[i+1]
                B[i] -= A[i+1]
                A[i+1] = 0
    counter += min(A[N-1] + A[N], B[N-1])
    print(counter)
    return


