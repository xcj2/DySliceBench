import sys


def solve(N: int, P: "List[int]"):
    pos = {n: i+1 for i, n in enumerate(P)}
    L1 = list(range(-1, N+1))
    L1[0] = 0
    L2 = list(range(-2, N))
    L2[0] = 0
    L2[1] = 0
    R1 = list(range(1, N+3))
    R1[-1] = N+1
    R2 = list(range(2, N+4))
    R2[-1] = N+1
    R2[-2] = N+1

    res = 0
    for i in range(1, N+1):
        s = pos[i]
        num = 0
        num += (R2[s] - R1[s]) * (s - L1[s])
        num += (L1[s] - L2[s]) * (R1[s] - s)
        res += i * num

        L1[R1[s]] = L1[s]
        L2[R1[s]] = L2[s]
        L2[R2[s]] = L1[s]
        R1[L1[s]] = R1[s]
        R2[L1[s]] = R2[s]
        R2[L2[s]] = R1[s]

    print(res)        
    return


