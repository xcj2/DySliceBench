import sys

Weather = input()

def Odd(x) :
  if x == 'L' :
    return True

def Even(x) :
  if x == 'R' :
    return True

def Step(Weather) :
  k =1
  for x in Weather :
    if k%2 ==1:
      if Odd(x) :
        break
      k+=1
    else:
      if Even(x) :
        break
      k+=1
  if k >len(Weather) :
    return True
  else :
    return False

if Step(Weather):
  print('Yes')
else :
  print('No')