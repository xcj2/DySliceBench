def solve(N: int, M: int, K: int, A: "List[int]", B: "List[int]"):

    sumA = [0]
    sum = 0
    for a in A:
        sum += a
        sumA.append(sum)
    sumB = [0]
    sum = 0
    for b in B:
        sum += b
        sumB.append(sum)
    
    
    # print(sumA)
    # print(sumB)
    # True - ng - ok - False
    def is_ok(mid: int, i):
        # 判定する条件
        if mid < 0:
            return True
        elif mid >= M + 1:
            return False
        # print(i, mid, sumA[i] + sumB[mid])
        return sumA[i] + sumB[mid] <= K

    def binSearch(ok: int, ng: int, i):
        # print(ok, ng)
        while abs(ok - ng) > 1:
            mid = (ok + ng) // 2
            if is_ok(mid, i):
                ok = mid
            else:
                ng = mid
            # print(ok, ng)
        return ok

    ans = 0
    for i in range(N + 1):
        j = binSearch(-1, M + 1, i)
        # print("a", i, j)
        if j < 0:
            break
        ans = max(ans, i + j)

    print(ans)
    return


