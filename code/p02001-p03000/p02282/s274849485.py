def calc(tree):
    if is_empty(right(tree)) or is_empty(left(tree)):
        return value(tree)

    if value(tree) == "+":
        return calc(right(tree)) + calc(left(tree))
    elif value(tree) == "-":
        return calc(right(tree)) - calc(left(tree))
    elif value(tree) == "*":
        return calc(right(tree)) * calc(left(tree))
    elif value(tree) == "/":
        return calc(right(tree)) / calc(left(tree))

