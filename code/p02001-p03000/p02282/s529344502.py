def rec(preo, ino):
    idx = -1
    proot = None # ??¨?????¨????????????
    for p in preo:
        if p in ino:
            idx = ino.index(p)
            proot = p
            break
    else:
        raise # unexpected error
    # ??????idx???????????\??£??????
    pleft = ino[:idx]
    pright = ino[idx+1:]
    prlen = len(pright)
    pllen = len(pleft)
    if prlen == 1:
        # ????????????pright??????????????????proot??????
        pright[0].parent = proot
        pright[0].depth = proot.depth + 1
        proot.right = pright[0]
    if pllen == 1:
        # ????????????pleft??????????????????proot??????
        pleft[0].parent = proot
        pleft[0].depth = proot.depth + 1
        proot.left = pleft[0]
    # ??°??????ino???????????????????????§????????????preo???????????£?????????
    if prlen > 1:
        for r in pright:
            r.parent = proot
            r.depth = proot.depth + 1
        pprt = rec(preo[1+pllen:], pright)
        proot.right = pprt
    if pllen > 1:
        for l in pleft:
            l.parent = proot
            l.depth = proot.depth + 1
        pprt = rec(preo[1:1+pllen], pleft)
        proot.left = pprt

    if prlen == 0: proot.right = None
    if pllen == 0: proot.left = None
    return proot

