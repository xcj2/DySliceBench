#!/usr/bin/env python3
import sys


def solve(N: int):
    L = factorization(N)
    sm = 0
    for l in L:
        if l[0] == 1:
            continue
        n = l[1]
        ct = 1
        while (ct + 1) * ct / 2 <= n:
            ct += 1
        sm += ct - 1

    print(sm)
    return


def factorization(n):
    arr = []
    temp = n
    for i in range(2, int(-(-n**0.5//1))+1):
        if temp%i==0:
            cnt=0
            while temp%i==0:
                cnt+=1
                temp //= i
            arr.append([i, cnt])

    if temp!=1:
        arr.append([temp, 1])

    if arr==[]:
        arr.append([n, 1])

    return arr

