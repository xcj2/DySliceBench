#!/usr/bin/env python3
import sys


def great_common_divisor(a, b):
    '''Calculate the great common divisor (GCD) of a and b
    Args:
        a (int) : value
        b (int) : value
    Returns:
        gcd (int) : the great common divisor of a and b
    Note:
        This function uses Euclidean Algorithm
    '''
    while b != 0:
        a, b = b, a % b
    return a

def least_common_multiple(a, b):
    '''Calculate the least common multiple (LCM) of a and b
    Args:
        a (int) : value
        b (int) : value
    Returns:
       lcm (int) : the least common multiple of a and b
    '''
    return (a * b) // great_common_divisor(a, b)



def solve(A: int, B: int, C: int, D: int):
    lcm = least_common_multiple(C, D)

    num_B = (B - B // C - B // D + B // lcm)

    # 「以上」「以下」の境界値に注意する。
    A = A - 1
    num_A = (A - A // C - A // D + A // lcm)

    print(num_B - num_A)
    return


