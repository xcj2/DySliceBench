def swap(A, x, y):
    i = A[x]
    A[x] = A[y]
    A[y] = i

def left(i):
    return i * 2

def right(i):
    return i * 2 + 1

def  maxHeapify(A, i, H):
    l = left(i)
    r = right(i)
    #  ????????????????????????????????§???????????§????????????????????¶
    if l <= H and A[l] > A[i]:
        largest = l
    else:
        largest = i
    if r <= H and A[r] > A[largest]:
        largest = r

    if largest != i: #// i ???????????????????????§????????´???
        swap(A, i, largest) # ??????
        maxHeapify(A, largest, H) # ?????°??????????????????

def buildMaxHeap(A, H):
    for i in range(int(H/2),0,-1):
        maxHeapify(A, i, H)

def main():

    """ ????????? """
    H = int(input().strip())
    A = [""]
    A.extend(list(map(int,input().split())))
    buildMaxHeap(A, H)
    print(" {}".format(" ".join(map(str,A[1:]))))

