#!/usr/bin/env python3
import sys


def solve(N: int, M: int, s: "List[int]", c: "List[int]"):
    restriction = [-1 for i in range(N)]
    for i in range(M):
        rC = s[i]-1
        rV = c[i]
        if restriction[rC] != -1 and restriction[rC] != rV:
            print("-1")
            return
        else:
            restriction[rC] = rV
    number = ""
    for i in range(N):
        if i == 0 and restriction[i] == 0:
            if N == 1:
                print("0")
                return
            print("-1")
            return
        if restriction[i] != -1:
            number+=str(restriction[i])
        else:
            number+="1" if i == 0 and N > 1 else "0"
    print(number)
    return


