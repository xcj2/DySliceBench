#!/usr/bin/env python3
import sys


def solve(N: int, M: int, s: "List[int]", c: "List[int]"):
    s = [x-1 for x in s]
    answer = 'x' * N
    head_flag = False
    for i in range(M):
        if list(answer)[s[i]] == 'x':
            answer = answer[:s[i]] + str(c[i]) + answer[s[i]+1:]
        else:
            if str(c[i]) != answer[s[i]]:
                print(-1)
                return
        if s[i] == 0 and c[i]==0:
            head_flag = True
    answer = ''.join(answer)
    answer = answer.replace('x', '0')
    answer = int(answer)
    answer = str(answer)
    if len(answer) != N and head_flag ==True:
        print(-1)
    elif len(answer) < N:
        answer = '1' + '0' * (N - len(answer) - 1) + answer
        print(answer)
    elif len(answer) == N:
        print(answer)
    else:
        print(-1)
    return


