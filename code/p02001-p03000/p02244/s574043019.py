    def is_available(self, pos):
        y, x = pos
        if self.situation[y][x] == '.':
            return True
        else:
            return False

    def get_availability(self):
        # ????????????????????????????????§??????????????????????????¨?????????????????¢??§??????
        results = []  # ??¨?????????????§£?????????
        for y in range(8):
            available = []  # ???????????§???????????????????????±
            for x in range(8):
                if self.situation[y][x] == '.':
                    available.append((y, x))
            if available:  # ????????´????????????????????????(itertools.product?????????????????????????????§)
                results.append(available)
        return results

    def get_empty_row(self):
        available = list(range(0, 8))
        for y, x in self.queen_pos:
            available.remove(y)
        return available

    def get_empty_col(self):
        available = list(range(0, 8))
        for y, x in self.queen_pos:
            available.remove(x)
        return available



