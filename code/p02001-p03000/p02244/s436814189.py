def solve(queens, B, r):
    global NUM,SETROW
    if r >= NUM:
        return True
    if r in SETROW:
        return solve(queens,B,r+1)
    else:
        for c in range(NUM):
            if B[r][c] == 0:
                ifed = True
                queens[r] = c
                reload_board(B,r,c,1)
                if not solve(queens,B,r+1):
                    reload_board(B,r,c,-1)
                else:
                    return True
    return False

def print_board(queens):
    for i in range(NUM):
        for j in range(NUM):
            print('Q' if queens[i] == j else '.', end='')
        print()

