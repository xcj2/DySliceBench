#!/usr/bin/env python3
import sys

MOD = 1000000007  # type: int

def solve(S: str):
    N = len(S)
    r_d = [1] * (N+1)
    r_d[0] = 0
    for i in range(2, N+1):
        r_d[i] = (r_d[i-1] * 10) % 13
    
    dp = [[0 for j in range(N+1)] for i in range(13)] # dp[i][j]: 13でわってiになるSのj桁目まで数の総数
    dp[0][0] = 1

    for j in range(1, N+1):
        d = S[-j]
        if d != "?":
            d = (int(d) * r_d[j]) % 13
            for i in range(13):
                dp[i][j] += dp[(i - d) % 13][j-1]
            continue
        for k in range(10):
            d = (k * r_d[j]) % 13
            for i in range(13):
                dp[i][j] += dp[(i - d) % 13][j-1]
                dp[i][j] %= MOD
    print(dp[5][N])
    return


