#!/usr/bin/env python3
import sys

MOD = 998244353  # type: int

def solve(N: int, S: str):
    # N = 2 * (10 ** 5)
    # S = 'R' * N + 'G' * N + 'B' * N
    c2n = {'R': 0, 'G': 1, 'B': 2}
    rgb = [[] for i in range(3)]

    for i, c in enumerate(S):
        c = c2n[c]
        rgb[c].append(i)
    
    S = [0] * N
    M = [0] * N
    L = [0] * N

    for i, t in enumerate(zip(*rgb)):
        S[i], M[i], L[i] = sorted(t)

    # print(S)
    # print(M)
    # print(L)
    # print("done")

    ri = [0] * 3 * N # ri[i]: iより大きいLの要素の数
    le = [0] * 3 * N

    j = N-1
    lj = L[j]
    count = 0
    for i in range(3*N-1, -1, -1):
        if i >= lj:
            ri[i] = count
            continue
        j -= 1
        lj = L[j] if j >= 0 else 0
        count += 1
        ri[i] = count

    j = 0
    sj = S[j]
    count = 0
    for i in range(3*N):
        if i <= sj:
            le[i] = count
            continue
        j += 1
        sj = S[j] if j <= N-1 else 3*N
        count += 1
        le[i] = count
    
    # print(ri)
    # print(le)

    res = 1
    for i, m in enumerate(M):
        cl = i
        cr = N-1-i
        res *= (le[m] - cl)
        res %= MOD
        res *= (ri[m] - cr)
        res %= MOD
    
    for i in range(1, N+1):
        res *= i
        res %= MOD
    
    print(res)
        
    return


