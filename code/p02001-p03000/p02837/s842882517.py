def chk(shoji, N, A, x, y):
    for chk in range(N):
        if shoji[chk]==0: continue
        for s in range(A[chk]):
            if ((y[chk][s]==1 and shoji[x[chk][s]-1]!=1) or 
                (y[chk][s]==0 and shoji[x[chk][s]-1]!=0)):
                return False
    return True

def solve(N: int, A: "List[int]", x: "List[int][int]", y: "List[int][int]"):
    fmt="0"+str(N)+"b"
    ans=0
    for kans in range(2**N):
        lst=list(format(kans,fmt))
        if chk([int(c) for c in lst], N, A, x, y):
            ans=max(ans, lst.count('1'))
    print(ans)
    return


