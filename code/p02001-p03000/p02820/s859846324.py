#!/usr/bin/env python3
import sys


def solve(N: int, K: int, R: int, S: int, P: int, T: str):
    # 案①
    # 1. 勝ちパターンに変換し点数を計算 2 * O(N)
    # 2. K番目以降を確認し点数の差分を計算 O(N)?
    # →手を修正すると、修正後の手に応じてその先の手も修正が必要になるのでこの方法は無理。
    #
    # 案②
    # 修正後の手も考慮しつつ探索すれば良さそう。
    # あいこと負けどちらを選ぶかは、K手先を見て決める
    # 計算量は大体 O((N/K) * K) = O(N)

    m = {'r': 'p', 's': 'r', 'p': 's'}
    nt = list(''.join([m[i] for i in T]))
    pm = {'r': R, 's': S, 'p': P}
    flgs = [0] * N
    ans = 0
    for i in range(N):
        if flgs[i]:
            continue
        piece = nt[i::K]
        for j, jv in enumerate(piece):
            if j - 1 >= 0 and jv == piece[j - 1]:
                jv = piece[j] = m[jv]
                if j + 1 < len(piece) and jv == piece[j + 1]:
                    jv = piece[j] = m[jv]
            else:
                ans += pm[jv]
            idx = i + (j * K)
            nt[idx] = jv
            flgs[idx] = 1
    print(ans)
    return


