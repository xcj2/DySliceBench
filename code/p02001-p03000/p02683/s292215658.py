#!/usr/bin/env python3
import sys
from itertools import product


def solve(N, M, X, C, A):
    L = list(product([True, False], repeat=N))
    mn = 100000000000
    for l in L:
        cst = 0
        rikai = [0 for _ in range(M)]
        for i in range(N):
            if l[i]:
                cst += C[i]
                for j in range(M):
                    rikai[j] += A[i][j]
        tf = True
        for j in range(M):
            if rikai[j] < X:
                tf = False
                break
        if tf:
            mn = min(mn, cst)
    if mn == 100000000000:
        print(-1)
    else:
        print(mn)
    return

