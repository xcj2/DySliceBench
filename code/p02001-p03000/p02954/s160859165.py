from itertools import groupby

def solve(S: str):
    lengths = [sum(1 for _ in g) for k, g in groupby(S)]
    cumsum=0
    a = [0]*len(S)
    for i in range(len(lengths)-1)[::2]:
        cumsum += lengths[i]
        a[cumsum-1]= lengths[i]//2 + lengths[i]%2   + lengths[i+1]//2
        a[cumsum]  = lengths[i]//2 + lengths[i+1]%2 + lengths[i+1]//2
        cumsum += lengths[i+1]

    return " ".join([str(child) for child in a])


