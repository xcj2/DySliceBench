#!/usr/bin/env python3
import sys


def solve(S: str):

    dest_list = [-1] * len(S)
    dest = -1
    clear_dest = False
    for i in range(len(S)-1):
        if clear_dest:
            dest = -1
            clear_dest = False

        if S[i] == "R" and S[i+1] == "L":
            dest = i
        elif S[i] == "L" and S[i+1] == "R":
            clear_dest = True
        dest_list[i] = dest
    dest_list[len(S)-1] = dest

    for i in range(len(S)-1,0,-1):
        if dest_list[i] != -1 and dest_list[i-1] == -1:
            dest_list[i-1] = dest_list[i]


    res = [0] * len(S)
    for i,d in enumerate(dest_list):
        diff = abs(i - d)
        if diff % 2 == 0:
            res[d] += 1
        else:
            res[d+1] += 1

    print(" ".join([str(i) for i in res]))

    return


