#!/usr/bin/env python3
import sys
import bisect

inf = float('inf')

def solve(S: str):
    N = len(S)
    rl = []
    for i in range(N-1):
        if S[i:i+2] == 'RL':
            rl.append(i+1)
    rl.append(inf)
    res = [0] * N
    j = 0
    rl_c = rl[j]
    for i, c in enumerate(S):
        if i >= rl_c:
            j += 1
            rl_c = rl[j]
            rl_p = rl[j-1]
        if c == 'R':
            diff = rl_c - i
            if diff % 2 == 0:
                res[rl_c] += 1
            else:
                res[rl_c-1] += 1
        else:
            diff = i - rl_p
            if diff % 2 == 0:
                res[rl_p] += 1
            else:
                res[rl_p-1] += 1
    print(' '.join(map(str, res)))
            
    return


