#!/usr/bin/env python3
import sys


def solve(S: str):
    batsu_list = []
    maru_list = []
    for idx, s in enumerate(S):
        if idx == len(S)-1:
            break
        if S[idx] == 'R' and S[idx+1] == 'L':
            batsu_list.append(idx+1)

    for idx, s in enumerate(S):
        if idx == 0:
            maru_list.append(idx)
        if idx == len(S)-1:
            break
        if S[idx] == 'L' and S[idx+1] == 'R':
            maru_list.append(idx+1)
    maru_list.append(len(S))

    result = [0 for s in S]
    for idx, batsu in enumerate(batsu_list):
        left = batsu_list[idx] - maru_list[idx]
        right = maru_list[idx+1] - batsu_list[idx]
        result[batsu-1] += left//2
        result[batsu] += left//2
        if left % 2 == 1:
            result[batsu-1] += 1
        result[batsu] += right//2
        result[batsu-1] += right//2
        if right % 2==1:
            result[batsu] += 1

    print(' '.join([str(i) for i in result]))
    return


