def solve(N: int, p: "List[int]"):

    if check(p):
        print("YES")
        return

    p1 = p.copy()
    if p[0] > p[1] and p[N-2] > p[N-1]:
        p1[0] = p[N-1]
        p1[N-1] = p[0]

    if check(p1):
        print("YES")
        return

    p2 = p.copy()
    current = p[0]
    for i in range(1, len(p)):
        if current > p[i]:
            p2[i-1] = p[i]
            p2[i] = p[i-1]
        current = p[i]

    if check(p2):
        print("YES")
        return

    p3 = p.copy()
    current = p[0]
    ind = 0
    hoge = [0] * 2

    for i in range(1, len(p)):
        if current > p[i]:
            if ind <= 1:
                hoge[ind] = i + ind - 1
                ind += 1
            else:
                print("NO")
                return
        current = p[i]

    if ind == 0 or ind == 1:
        print("NO")
        return

    p3[hoge[0]] = p[hoge[1]]
    p3[hoge[1]] = p[hoge[0]]
    if check(p3):
        print("YES")
        return
    else:
        print("NO")
        return



def check(p):
    # print(p)
    current = p[0]
    for i in range(1, len(p)):
        # print(current)
        if current > p[i]:
            return False
        current = p[i]

    return True

