import sys

class Node:
    def __init__(self,v):
        self.value = v
        self.next = None
        self.prev = None
    
    def insertHead(self,v):
        self.prev = v
        v.next = self
        return v

    def appendBottom(self,v):
        self.next = v
        v.prev = self
        return v

    def printRecursively(self):
        current = self
        s = ""
        while True:
            if current == None:
                break
            s += current.value
            current = current.next
        print(s)

    def printRecursivelyInvert(self):
        current = self
        s = ""
        while True:
            if current == None:
                break
            s += current.value
            current = current.prev
        print(s)

