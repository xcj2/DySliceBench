import sys
sys.setrecursionlimit(2_000_000)

def solve(H, W, CH, DH, CW, DW, S):
    from collections import deque
    costs = [[float("inf")] * W for _ in range(H)]
    
    def bfs():
        q = deque([(CH-1, CW-1, 0)])
        while q:
            h, w, c = q.popleft()
            if h == (DH-1) and w == (DW-1):
                return c
            if costs[h][w] < c:
                continue
            costs[h][w] = c
            for dh, dw in zip((0, 0, 1, -1), (1, -1, 0, 0)):
                nh, nw = h + dh, w + dw
                if not (0 <= nh < H and 0 <= nw < W):
                    continue
                if S[nh][nw] == "#":
                    continue
                if costs[nh][nw] <= c:
                    continue
                costs[nh][nw] = c
                q.appendleft((nh, nw, c))
            for dh in range(-2, 3):
                for dw in range(-2, 3):
                    nh, nw = h + dh, w + dw
                    if not (0 <= nh < H and 0 <= nw < W):
                        continue
                    if S[nh][nw] == "#":
                        continue
                    if costs[nh][nw] <= (c + 1):
                        continue
                    costs[nh][nw] = c+1
                    q.append((nh, nw, c+1))
        return -1
    
    return bfs()

    
