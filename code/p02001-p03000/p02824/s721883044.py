import sys


def solve(N: int, M: int, V: int, P: int, A: "List[int]"):

    A.sort(reverse=True)

    I = N

    for i in range(P, N):
        if A[P-1] > A[i] + M:
            I = i
            break

    l = P-1
    r = I
    m = (l + r)//2

    while l + 1 != r:

        k = (V-P)*M - M*(N-I)
        for i in range(P-1, I):
            if i == m:
                continue
            k -= min(A[m] + M -A[i], M)
            if k <= 0:
                l = m
                m = (l+r)//2
                break
        if k > 0:
            r = m
            m = (l+r)//2

    print(l+1)







    return


