def bs(f, mi, ma):
    mm = -1
    while ma > mi:
        mm = (ma+mi) // 2
        if f(mm):
            mi = mm + 1
        else:
            ma = mm
    if f(mm):
        return mm + 1
    return mm

def main():
    n,m,v,p = LI()
    a = sorted(LI())
    pi = n-p
    pv = a[pi]

    def f(i):
        t = a[i] + m
        if pv > t:
            return True
        mv = m*v-m
        for j in range(n):
            if j == i:
                continue
            aj = a[j]
            if j > pi:
                mv -= m
            elif aj <= t:
                mv -= min(m, t - aj)
            else:
                mv -= m
        return mv > 0

    r = bs(f,0,n-1)

    return n - r


