import sys

MOD = 1000000007  # type: int


def solve(n: int, a: int, b: int):
    al = modPow(2, n, MOD) - 1
    # aに対して
    X = 1
    # 分子
    for i in range(a):
        X = (X * (n - i)) % MOD
    Y = 1
    # Y
    for i in range(a):
        Y = (Y * (a - i)) % MOD
    a_val = (X * modPow(Y, MOD - 2, MOD)) % MOD

    # bに対して
    X = 1
    # 分子
    for i in range(b):
        X = (X * (n - i)) % MOD
    Y = 1
    # Y
    for i in range(b):
        Y = (Y * (b - i)) % MOD
    b_val = (X * modPow(Y, MOD - 2, MOD)) % MOD

    print((al - a_val - b_val) % MOD)


def modPow(a: int, n: int, p: int):
    if n == 1:
        return a
    elif n % 2 == 0:
        n2 = modPow(a, n / 2, p)
        return pow(n2, 2) % p
    else:
        return (a * modPow(a, n - 1, p)) % p


