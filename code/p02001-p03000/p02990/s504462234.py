#!/usr/bin/env python3
import sys
from collections import defaultdict


MOD = 1000000007  # type: int

memo = dict()

def comb(n, k):
    if k < 0:
        return 0
    if n < k:
        return 0
    
    if (n, k) in memo:
        pass
    elif k == 0:
        memo[(n, k)] = 1
    elif 2 * k > n:
        memo[(n, k)] = comb(n, n-k)
    else:
        memo[(n, k)] = (comb(n, k-1) * (n - k + 1) // k)
    return memo[(n, k)]
    

def solve(N: int, K: int):
    for n in range(1, K+1):
        blue = comb(K-1, n-1)
        red = comb(N-K+1, n)
        print((blue * red) % MOD)

    return


