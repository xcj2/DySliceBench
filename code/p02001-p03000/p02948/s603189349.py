def solve(N: int, M: int, A: "List[int]", B: "List[int]"):
    mix_list = [[a, b] for a, b in zip(A, B)]
    mix_list = sorted(mix_list, key=lambda x:(x[0], x[1]))
    A, B = zip(*mix_list)

    heap = []
    heapq.heapify(heap)

    head = 0
    earned = 0
    for i in range(1, M+1):
        while (head < len(A)) and (A[head] <= i):
            heapq.heappush(heap, -B[head])
            head += 1
        if len(heap) == 0:
            pass
        else:
            accepted = -heapq.heappop(heap)
            earned += accepted
    print(earned)



