def solve(N: int, a: "List[int]"):
    a = [0] + a
    result = [0 for i in range(N+1)]
    for i in range(N, 0, -1):
        bai = 1

        summation = 0
        while bai * i <= N:
            summation += result[bai * i]
            bai += 1

        if a[i] == 0:
            if summation % 2 == 0:
                result[i] = 0
            else:
                result[i] = 1
        else:
            if summation % 2 == 0:
                result[i] = 1
            else:
                result[i] = 0
                
    print(sum(result))

    if sum(result) > 0:
        output = ''
        for i in range(1, N+1):
            if result[i] == 1:
                output += ' %d' % (i)
        print(output[1:])
    
    return


