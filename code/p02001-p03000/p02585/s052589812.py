#!/usr/bin/env python3
import sys


def solve(N: int, K: int, P: "List[int]", C: "List[int]"):
    res = - 10 ** 10
    for i in range(N):
        lmax = - 10 ** 10
        nlmax = 0
        cp = P[i] - 1
        cl = 1
        cs = C[cp]
        css = []
        css.append(cs)
        while cp != i:
            if cs > lmax and cl <= K:
                lmax = cs
                nlmax = cl
            cp = P[cp] - 1
            cl += 1
            cs += C[cp]
            css.append(cs)
        if cs > lmax and cl <= K:
            lmax = cs
            nlmax = cl
        syc = cs
        length = cl
        # nloop = max(0, (K - nlmax) // length)
        nloop = max(0, K // length - 1)
        x = K % length
        if K // length >= 1:
            nokori = lmax
            for j in range(x):
                nokori = max(nokori, syc + css[j])
        else:
            nokori = lmax
        res = max(res, max(lmax, syc * nloop + nokori))
        # print((i, syc, lmax, nlmax, length))
    print(res)
    return


